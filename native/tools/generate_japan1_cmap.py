#!/usr/bin/env python3
"""Generate compact Adobe-Japan1 CMap tables for the native bridge.

Inputs are the Adobe CMap resources shipped by Poppler/Ghostscript:
  90ms-RKSJ-H       code -> CID
  Adobe-Japan1-UCS2 CID -> Unicode scalar

The generated include is data, not hand-maintained code.
"""
import re
import sys
from pathlib import Path


def hex4(value: str) -> int:
    return int(value, 16)


def parse_cid_ranges(path: Path):
    text = path.read_text(encoding="latin-1")
    ranges = []
    for block in re.finditer(r"begincidrange(.*?)endcidrange", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s+(\d+)", line)
            if m:
                ranges.append((hex4(m.group(1)), hex4(m.group(2)), int(m.group(3))))
    for block in re.finditer(r"begincidchar(.*?)endcidchar", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s+(\d+)", line)
            if m:
                code = hex4(m.group(1))
                ranges.append((code, code, int(m.group(2))))
    return ranges


def parse_unicode_ranges(path: Path):
    text = path.read_text(encoding="latin-1")
    pairs = []
    for block in re.finditer(r"beginbfchar(.*?)endbfchar", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>", line)
            if m:
                pairs.append((hex4(m.group(1)), hex4(m.group(2))))
    for block in re.finditer(r"beginbfrange(.*?)endbfrange", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(
                r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>", line
            )
            if m:
                lo, hi, start = hex4(m.group(1)), hex4(m.group(2)), hex4(m.group(3))
                for offset in range(hi - lo + 1):
                    pairs.append((lo + offset, start + offset))
    merged = {}
    for cid, unicode in pairs:
        if 0 <= unicode <= 0x10FFFF and not 0xD800 <= unicode <= 0xDFFF:
            merged[cid] = unicode
    return sorted(merged.items())


def emit(path: Path, ranges, unicode_pairs):
    # Collapse adjacent code ranges and adjacent CID->Unicode increments.
    code_ranges = []
    for lo, hi, cid in sorted(ranges):
        if code_ranges and code_ranges[-1][1] + 1 == lo and code_ranges[-1][2] + (lo - code_ranges[-1][0]) == cid:
            code_ranges[-1] = (code_ranges[-1][0], hi, code_ranges[-1][2])
        else:
            code_ranges.append((lo, hi, cid))
    unicode_ranges = []
    for cid, unicode in unicode_pairs:
        if unicode_ranges and unicode_ranges[-1][1] + 1 == cid and unicode_ranges[-1][2] + (cid - unicode_ranges[-1][0]) == unicode:
            unicode_ranges[-1] = (unicode_ranges[-1][0], cid, unicode_ranges[-1][2])
        else:
            unicode_ranges.append((cid, cid, unicode))
    with path.open("w", encoding="utf-8") as out:
        out.write("// Generated by native/tools/generate_japan1_cmap.py. Do not edit.\n")
        out.write("// Data: Adobe-Japan1 CMap resources (90ms-RKSJ-H, Adobe-Japan1-UCS2).\n")
        out.write("struct Japan1CodeRange { uint16_t lo, hi; uint32_t cid; };\n")
        out.write("static constexpr Japan1CodeRange kJapan1CodeRanges[] = {\n")
        for lo, hi, cid in code_ranges:
            out.write(f"    {{0x{lo:04X}, 0x{hi:04X}, {cid}}},\n")
        out.write("};\n")
        out.write("struct Japan1UnicodeRange { uint16_t cidLo, cidHi; uint32_t unicode; };\n")
        out.write("static constexpr Japan1UnicodeRange kJapan1UnicodeRanges[] = {\n")
        for lo, hi, unicode in unicode_ranges:
            out.write(f"    {{0x{lo:04X}, 0x{hi:04X}, 0x{unicode:04X}}},\n")
        out.write("};\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit("usage: generate_japan1_cmap.py <90ms-RKSJ-H> <Adobe-Japan1-UCS2> <out.inc>")
    ranges = parse_cid_ranges(Path(sys.argv[1]))
    unicode_pairs = parse_unicode_ranges(Path(sys.argv[2]))
    emit(Path(sys.argv[3]), ranges, unicode_pairs)
    print(f"code ranges={len(ranges)} unicode pairs={len(unicode_pairs)}")
