#!/usr/bin/env python3
"""Generate compact Adobe CJK CMap tables (Japan1, Korea1, GB1) for the native bridge.

Inputs are Adobe CMap resources shipped by Poppler/Ghostscript.
The generated includes are data tables, not hand-maintained code.
"""
import re
import sys
from pathlib import Path


def hex4(value: str) -> int:
    return int(value, 16)


def reject_inherited_cmap(path: Path, text: str):
    if re.search(r"(?m)^\s*\S+\s+usecmap\b", text):
        raise SystemExit(f"{path}: inherited CMaps (usecmap) are not supported")


def parse_cid_ranges(path: Path):
    text = path.read_text(encoding="latin-1")
    reject_inherited_cmap(path, text)
    ranges = []
    for block in re.finditer(r"begincidrange(.*?)endcidrange", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s+(\d+)", line)
            if m:
                lo, hi = hex4(m.group(1)), hex4(m.group(2))
                if lo > 0xFFFF or hi > 0xFFFF or hi < lo:
                    raise SystemExit(f"{path}: source code outside the 16-bit table")
                ranges.append((lo, hi, int(m.group(3))))
    for block in re.finditer(r"begincidchar(.*?)endcidchar", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s+(\d+)", line)
            if m:
                code = hex4(m.group(1))
                if code > 0xFFFF:
                    raise SystemExit(f"{path}: source code outside the 16-bit table")
                ranges.append((code, code, int(m.group(2))))
    return ranges


def decode_utf16be_hex(value: str):
    """Return the first Unicode scalar encoded by a UTF-16BE hex string.

    Adobe UCS2 CMaps occasionally map a CID to a base character followed by a
    variation selector (for example ``0030FE00``), or to a surrogate pair. The
    generated table stores one scalar per CID, so combine a valid surrogate
    pair and otherwise keep the first code unit.
    """
    if not value or len(value) % 4:
        return None
    units = [int(value[i : i + 4], 16) for i in range(0, len(value), 4)]
    first = units[0]
    if 0xD800 <= first <= 0xDBFF and len(units) > 1 and 0xDC00 <= units[1] <= 0xDFFF:
        return 0x10000 + ((first - 0xD800) << 10) + (units[1] - 0xDC00)
    if 0xD800 <= first <= 0xDFFF:
        return None
    return first


def parse_unicode_ranges(path: Path):
    text = path.read_text(encoding="latin-1")
    reject_inherited_cmap(path, text)
    pairs = []
    for block in re.finditer(r"beginbfchar(.*?)endbfchar", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>", line)
            if m:
                pairs.append((hex4(m.group(1)), decode_utf16be_hex(m.group(2))))
    for block in re.finditer(r"beginbfrange(.*?)endbfrange", text, re.S):
        for line in block.group(1).splitlines():
            m = re.match(
                r"\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>\s*<([0-9a-fA-F]+)>", line
            )
            if m:
                lo, hi = hex4(m.group(1)), hex4(m.group(2))
                start = decode_utf16be_hex(m.group(3))
                if start is None or hi < lo:
                    continue
                for offset in range(hi - lo + 1):
                    pairs.append((lo + offset, start + offset))
    merged = {}
    for cid, unicode in pairs:
        if unicode is not None and 0 <= unicode <= 0x10FFFF and not 0xD800 <= unicode <= 0xDFFF:
            merged[cid] = unicode
    return sorted(merged.items())


def collapse_code_ranges(ranges):
    collapsed = []
    for lo, hi, cid in sorted(ranges):
        if (
            collapsed
            and collapsed[-1][1] + 1 == lo
            and collapsed[-1][2] + (lo - collapsed[-1][0]) == cid
        ):
            collapsed[-1] = (collapsed[-1][0], hi, collapsed[-1][2])
        else:
            collapsed.append((lo, hi, cid))
    return collapsed


def emit(path: Path, ranges, vert_ranges, unicode_pairs, tag: str, ordering: str, cmap_names: str, ucs2_name: str):
    code_ranges = collapse_code_ranges(ranges)
    vert_code_ranges = collapse_code_ranges(vert_ranges)
    unicode_ranges = []
    for cid, unicode in unicode_pairs:
        if unicode_ranges and unicode_ranges[-1][1] + 1 == cid and unicode_ranges[-1][2] + (cid - unicode_ranges[-1][0]) == unicode:
            unicode_ranges[-1] = (unicode_ranges[-1][0], cid, unicode_ranges[-1][2])
        else:
            unicode_ranges.append((cid, cid, unicode))
    with path.open("w", encoding="utf-8") as out:
        out.write(f"// Generated by native/tools/generate_cjk_cmap.py. Do not edit.\n")
        out.write(f"// Data: Adobe-{ordering} CMap resources ({cmap_names}, {ucs2_name}).\n")
        out.write(f"// Copyright 1990-2019 Adobe. All rights reserved. See native/licenses/ADOBE-CMAPS.txt.\n")
        out.write(f"struct {tag}CodeRange {{ uint16_t lo, hi; uint32_t cid; }};\n")
        out.write(f"static constexpr {tag}CodeRange k{tag}CodeRanges[] = {{\n")
        for lo, hi, cid in code_ranges:
            out.write(f"    {{0x{lo:04X}, 0x{hi:04X}, {cid}}},\n")
        out.write("};\n")
        if vert_code_ranges:
            out.write(f"static constexpr {tag}CodeRange k{tag}VertCodeRanges[] = {{\n")
            for lo, hi, cid in vert_code_ranges:
                out.write(f"    {{0x{lo:04X}, 0x{hi:04X}, {cid}}},\n")
            out.write("};\n")
        out.write(f"struct {tag}UnicodeRange {{ uint16_t cidLo, cidHi; uint32_t unicode; }};\n")
        out.write(f"static constexpr {tag}UnicodeRange k{tag}UnicodeRanges[] = {{\n")
        for lo, hi, unicode in unicode_ranges:
            out.write(f"    {{0x{lo:04X}, 0x{hi:04X}, 0x{unicode:04X}}},\n")
        out.write("};\n")
    print(f"Wrote {path}: {len(code_ranges)} code ranges, {len(vert_code_ranges)} vert ranges, {len(unicode_ranges)} unicode ranges")


if __name__ == "__main__":
    if len(sys.argv) not in (6, 7):
        raise SystemExit("usage: generate_cjk_cmap.py <code-cmap> <ucs2-cmap> <out.inc> <Tag> <Ordering> [vert-cmap]")
    cmap_p = Path(sys.argv[1])
    ucs2_p = Path(sys.argv[2])
    out_p = Path(sys.argv[3])
    tag = sys.argv[4]
    ordering = sys.argv[5]
    vert_p = Path(sys.argv[6]) if len(sys.argv) == 7 else None
    ranges = parse_cid_ranges(cmap_p)
    vert_ranges = parse_cid_ranges(vert_p) if vert_p else []
    unicode_pairs = parse_unicode_ranges(ucs2_p)
    cmap_names = f"{cmap_p.name}, {vert_p.name}" if vert_p else cmap_p.name
    emit(out_p, ranges, vert_ranges, unicode_pairs, tag, ordering, cmap_names, ucs2_p.name)
