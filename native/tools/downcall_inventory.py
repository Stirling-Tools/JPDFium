#!/usr/bin/env python3
"""Regenerates docs/design/JAVA_MIGRATION_INVENTORY.md from the Java FFM bindings."""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JAVA = ROOT / "jpdfium" / "src" / "main" / "java"
OUT = ROOT / "docs" / "design" / "JAVA_MIGRATION_INVENTORY.md"
GUARDS = ROOT / "native" / "bridge" / "src" / "legacy"

DOWNCALL = re.compile(r'\b(downcall|downcallOptional|find)\(\s*"([A-Za-z0-9_]*[A-Za-z0-9])"', re.S)
JEXTRACT = re.compile(r"\bJpdfiumH\.(jpdfium_[a-z0-9_]+)\(")

# Bridge entry points that wrap a non-PDFium library; everything else is assumed to reach PDFium.
NON_PDFIUM = re.compile(
    r"^jpdfium_(rust_|has_rust|abi_|free_|icu_|pcre2_|flashtext_|font_(classify|subset|covers_text|free_info)|text_shape|luhn_|glyph_|qpdf_|brotli_|lcms_|openjpeg_|unibreak_)"
)

SAFE = {
    "jpdfium_init": "jpdf_runtime_init",
    "jpdfium_init_ex": "jpdf_runtime_init",
    "jpdfium_destroy": "jpdf_runtime_shutdown",
    "jpdfium_doc_open": "jpdf_doc_open_file",
    "jpdfium_doc_open_protected": "jpdf_doc_open_file",
    "jpdfium_doc_close": "jpdf_doc_close",
    "jpdfium_doc_page_count": "jpdf_doc_page_count",
    "jpdfium_page_open": "jpdf_page_open",
    "jpdfium_page_close": "jpdf_page_close",
    "jpdfium_page_width": "jpdf_page_get_info",
    "jpdfium_page_height": "jpdf_page_get_info",
    "jpdfium_page_info": "jpdf_page_get_info",
    "jpdfium_render_page": "jpdf_page_render",
    "jpdfium_render_page_flags": "jpdf_page_render",
    "jpdfium_free_buffer": "jpdf_bitmap_close",
    "FPDF_GetPageCount": "jpdf_doc_page_count",
    "FPDF_LoadPage": "jpdf_page_open",
    "FPDF_ClosePage": "jpdf_page_close",
    "FPDF_GetPageWidthF": "jpdf_page_get_info",
    "FPDF_GetPageHeightF": "jpdf_page_get_info",
    "FPDF_GetPageWidth": "jpdf_page_get_info",
    "FPDF_GetPageHeight": "jpdf_page_get_info",
    "FPDFPage_GetRotation": "jpdf_page_get_info",
    "FPDF_RenderPageBitmap": "jpdf_page_render",
    "FPDF_RenderPageBitmapWithMatrix": "jpdf_page_render",
    "FPDFBitmap_Create": "jpdf_page_render",
    "FPDFBitmap_CreateEx": "jpdf_page_render",
    "FPDFBitmap_FillRect": "jpdf_page_render",
    "FPDFBitmap_Destroy": "jpdf_bitmap_close",
}


def touches_pdfium(symbol: str) -> str:
    if symbol.startswith(("FPDF", "EPDF", "FORM_")):
        return "yes"
    return "no" if NON_PDFIUM.match(symbol) else "yes"


def guarded_symbols() -> set[str]:
    names = set()
    for path in GUARDS.glob("guards_*.cpp"):
        names |= set(re.findall(r"\bjpdf_guard_(\w+)\(", path.read_text(encoding="utf-8")))
    return names


def domain(symbol: str, guarded: set[str]) -> str:
    if symbol in guarded:
        return "guarded"
    return "unguarded" if touches_pdfium(symbol) == "no" else "unadmitted"


def main() -> int:
    by_class: dict[str, set[tuple[str, str]]] = defaultdict(set)
    for path in sorted(JAVA.rglob("*.java")):
        text = path.read_text(encoding="utf-8")
        name = path.stem
        for kind, symbol in DOWNCALL.findall(text):
            by_class[name].add((symbol, "lookup" if kind == "find" else kind))
        for symbol in JEXTRACT.findall(text):
            by_class[name].add((symbol, "jextract"))

    guarded = guarded_symbols()
    symbols = {s for entries in by_class.values() for s, _ in entries}
    pdfium = sum(1 for s in symbols if touches_pdfium(s) == "yes")
    mapped = sum(1 for s in symbols if s in SAFE)
    via_guard = sum(1 for s in symbols if s in guarded)
    lines = [
        "# Java downcall inventory",
        "",
        "Generated by `native/tools/downcall_inventory.py`; do not edit by hand.",
        "",
        f"{len(symbols)} distinct native symbols across {len(by_class)} Java classes. "
        f"{pdfium} reach PDFium; {via_guard} are bound through a native `jpdf_guard_*` shim; "
        f"{mapped} already have a safe `jpdf_*` replacement.",
        "",
        "`PDFium` is name-based: bridge wrappers around other libraries count as `no`. "
        "Confirm each entry against its C++ body when migrating it. `Domain` is `guarded` when the "
        "Java binding reaches it through its guard shim, `unguarded` for PDFium-free entry points, "
        "and `unadmitted` when a PDFium-touching symbol has no guard shim.",
        "",
    ]
    for cls in sorted(by_class):
        lines += [f"## {cls}", "", "| Symbol | Binding | PDFium | Domain | Safe replacement |",
                  "|---|---|---|---|---|"]
        for symbol, kind in sorted(by_class[cls]):
            safe = SAFE.get(symbol, "pending")
            lines.append(f"| `{symbol}` | {kind} | {touches_pdfium(symbol)} | "
                         f"{domain(symbol, guarded)} | {safe} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(symbols)} symbols, {pdfium} PDFium, "
          f"{via_guard} guarded, {mapped} mapped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
