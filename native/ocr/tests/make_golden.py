"""Records reference outputs for ocr_geometry.cpp from the real PaddleOCR stack.

Run with the PaddleOCR 3.7 reference environment (paddlex 3.7.2, OpenCV 4.10, pyclipper):
  python native/ocr/tests/make_golden.py > native/ocr/tests/ocr_golden.inc
Inputs come from the same LCG as the C++ test, so only outputs are stored.
"""

from __future__ import annotations

import hashlib

import cv2
import numpy as np
from paddlex.inference.models.text_detection.processors import (
    DBPostProcess,
    DetResizeForTest,
    NormalizeImage,
)
from paddlex.inference.models.text_recognition.processors import OCRReisizeNormImg
from paddlex.inference.pipelines.components.common.crop_image_regions import CropByPolys
from paddlex.inference.pipelines.components.common.sort_boxes import SortQuadBoxes


class Lcg:
    def __init__(self, seed: int) -> None:
        self.state = seed & 0xFFFFFFFF

    def next(self) -> int:
        self.state = (self.state * 1664525 + 1013904223) & 0xFFFFFFFF
        return self.state >> 8


def image(seed: int, w: int, h: int) -> np.ndarray:
    rng = Lcg(seed)
    return np.array([rng.next() & 0xFF for _ in range(w * h * 3)], np.uint8).reshape(h, w, 3)


def prob_map(seed: int, w: int, h: int, rects) -> np.ndarray:
    """Noise below the threshold, with brighter rectangles (x0, y0, x1, y1) on top."""
    rng = Lcg(seed)
    out = np.zeros((h, w), np.float32)
    for y in range(h):
        for x in range(w):
            inside = any(x0 <= x <= x1 and y0 <= y <= y1 for x0, y0, x1, y1 in rects)
            k = rng.next() % 500
            out[y, x] = np.float32((500 + k) / 1000.0) if inside else np.float32(k / 2000.0)
    return out


def digest(a: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()


def emit(name: str, value) -> None:
    print(f"constexpr auto {name} = {value};")


print("// ocr_golden.inc - generated by make_golden.py from the PaddleOCR 3.7 reference stack.")
print("// Do not edit; regenerate when the reference changes.")

# cv2.resize, INTER_LINEAR
for i, (seed, sw, sh, dw, dh) in enumerate([(1, 7, 5, 11, 9), (2, 13, 11, 4, 3), (3, 40, 9, 97, 48),
                                            (4, 300, 60, 160, 48), (5, 33, 17, 32, 32)]):
    out = cv2.resize(image(seed, sw, sh), (dw, dh))
    emit(f"kResize{i}", f'"{digest(out)}"')

# cv2.warpPerspective(INTER_CUBIC, BORDER_REPLICATE) through get_rotate_crop_image's geometry
for i, (seed, sw, sh, quad, dw, dh) in enumerate([
    (6, 40, 30, [[3, 4], [33, 4], [33, 20], [3, 20]], 30, 16),
    (7, 40, 30, [[5.5, 3.25], [35.75, 6.5], [33.0, 24.0], [2.5, 21.0]], 31, 18),
    (8, 64, 48, [[10, 40], [12, 5], [30, 7], [28, 42]], 18, 35),
]):
    src = np.float32(quad)
    dst = np.float32([[0, 0], [dw, 0], [dw, dh], [0, dh]])
    m = cv2.getPerspectiveTransform(src, dst)
    out = cv2.warpPerspective(image(seed, sw, sh), m, (dw, dh), borderMode=cv2.BORDER_REPLICATE,
                              flags=cv2.INTER_CUBIC)
    emit(f"kWarp{i}", f'"{digest(out)}"')

# DBPostProcess end to end (contours, min-area boxes, scores, unclip) on synthetic maps
post = DBPostProcess(thresh=0.3, box_thresh=0.6, max_candidates=3000, unclip_ratio=1.5)
for i, (seed, w, h, rects, dest) in enumerate([
    (9, 64, 48, [(5, 5, 40, 12), (8, 20, 55, 30), (50, 35, 60, 44)], (128, 96)),
    (10, 96, 64, [(2, 2, 90, 8), (10, 15, 20, 60), (30, 20, 34, 24), (40, 30, 80, 50)], (101, 77)),
    (11, 48, 48, [(0, 0, 47, 3), (20, 20, 21, 21), (10, 30, 40, 40)], (48, 48)),
]):
    pred = prob_map(seed, w, h, rects)
    boxes, scores = post.boxes_from_bitmap(pred, pred > 0.3, dest[0], dest[1], 0.6, 1.5)
    boxes = SortQuadBoxes()(boxes)
    flat = ", ".join(str(int(v)) for b in boxes for v in np.array(b).reshape(-1))
    emit(f"kDetect{i}Count", len(boxes))
    emit(f"kDetect{i}Boxes", f"std::array<int, {8 * len(boxes)}>{{{flat}}}")

# DetResizeForTest + NormalizeImage (BGR order, hwc), as the text detection predictor builds it
for i, (seed, w, h) in enumerate([(12, 50, 30), (13, 130, 70), (14, 20, 12)]):
    resize = DetResizeForTest(limit_side_len=64, limit_type="min", max_side_limit=4000)
    imgs, _ = resize([image(seed, w, h)], 64, "min", 4000)
    norm = NormalizeImage(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225],
                          scale="1./255.", order="hwc")
    tensor = np.transpose(norm(imgs)[0], (2, 0, 1)).astype(np.float32)
    emit(f"kDetInput{i}Shape", f"std::array<int, 2>{{{tensor.shape[1]}, {tensor.shape[2]}}}")
    emit(f"kDetInput{i}", f'"{digest(tensor)}"')

# CropByPolys(quad) on integer boxes, including a tall one that is turned
crop = CropByPolys(det_box_type="quad")
for i, (seed, w, h, box) in enumerate([
    (15, 80, 60, [[4, 6], [70, 6], [70, 20], [4, 20]]),
    (16, 80, 60, [[10, 10], [60, 14], [58, 30], [8, 26]]),
    (17, 80, 60, [[30, 2], [44, 2], [44, 55], [30, 55]]),
]):
    out = crop.get_minarea_rect_crop(image(seed, w, h), np.array(box, np.int16))
    emit(f"kCrop{i}Shape", f"std::array<int, 2>{{{out.shape[1]}, {out.shape[0]}}}")
    emit(f"kCrop{i}", f'"{digest(np.ascontiguousarray(out))}"')

# OCRReisizeNormImg for single crops (batch padding is plain zeros)
rec = OCRReisizeNormImg(rec_image_shape=[3, 48, 320])
for i, (seed, w, h) in enumerate([(18, 90, 30), (19, 700, 40), (20, 2000, 20), (21, 25, 60)]):
    tensor = rec([image(seed, w, h)])[0].astype(np.float32)
    emit(f"kRec{i}Width", tensor.shape[2])
    emit(f"kRec{i}", f'"{digest(tensor)}"')
