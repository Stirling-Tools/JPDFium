// Regenerates the ICU sentence-break goldens used by
// SentenceSegmentationParityTest. Not part of any build; run it by hand.
//
//   c++ -O2 -std=c++17 $(pkg-config --cflags icu-i18n) \
//       icu_sentence_golden.cpp -o icu_sentence_golden $(pkg-config --libs icu-i18n)
//   ./icu_sentence_golden ../../../jpdfium/src/test/resources/pii/sentence-corpus.tsv \
//                         ../../../jpdfium/src/test/resources/pii/sentence-goldens.tsv
//
// The boundaries are produced by the same API the dropped native bridge used:
// icu::BreakIterator::createSentenceInstance(...) + first()/next() over a
// UTF-16 string, so the offsets are UTF-16 code units, exactly what
// jpdfium_icu_break_sentences returned and what java.text.BreakIterator
// reports. Locale::getRoot() is used for the goldens; the generator also
// recomputes with Locale::getDefault() and fails loudly if the two disagree
// on any corpus entry, which would mean the goldens are environment-dependent.

#include <unicode/brkiter.h>
#include <unicode/locid.h>
#include <unicode/unistr.h>

#include <cstdio>
#include <fstream>
#include <memory>
#include <sstream>
#include <string>
#include <vector>

namespace {

struct Case {
    std::string id;
    std::u16string text;
};

// Decodes \\n, \\t, \\\\ and \\uXXXX (Java style) into UTF-16.
bool decodeEscapes(const std::string& in, std::u16string* out) {
    for (size_t i = 0; i < in.size(); ++i) {
        char c = in[i];
        if (c != '\\') {
            out->push_back(static_cast<char16_t>(static_cast<unsigned char>(c)));
            continue;
        }
        if (++i >= in.size()) return false;
        switch (in[i]) {
            case 'n': out->push_back(u'\n'); break;
            case 't': out->push_back(u'\t'); break;
            case 'r': out->push_back(u'\r'); break;
            case '\\': out->push_back(u'\\'); break;
            case 'u': {
                if (i + 4 >= in.size()) return false;
                unsigned value = 0;
                for (int d = 0; d < 4; ++d) {
                    char h = in[++i];
                    value <<= 4;
                    if (h >= '0' && h <= '9') value |= static_cast<unsigned>(h - '0');
                    else if (h >= 'a' && h <= 'f') value |= static_cast<unsigned>(h - 'a' + 10);
                    else if (h >= 'A' && h <= 'F') value |= static_cast<unsigned>(h - 'A' + 10);
                    else return false;
                }
                out->push_back(static_cast<char16_t>(value));
                break;
            }
            default: return false;
        }
    }
    return true;
}

bool readCorpus(const char* path, std::vector<Case>* cases, std::string* error) {
    std::ifstream in(path, std::ios::binary);
    if (!in) { *error = "cannot open corpus"; return false; }
    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty() || line[0] == '#') continue;
        size_t tab = line.find('\t');
        if (tab == std::string::npos) { *error = "corpus line without tab: " + line; return false; }
        Case c;
        c.id = line.substr(0, tab);
        if (!decodeEscapes(line.substr(tab + 1), &c.text)) {
            *error = "bad escapes in " + c.id;
            return false;
        }
        cases->push_back(std::move(c));
    }
    return true;
}

bool boundaries(const icu::Locale& locale, const std::u16string& text,
                std::vector<int32_t>* out, std::string* error) {
    UErrorCode status = U_ZERO_ERROR;
    std::unique_ptr<icu::BreakIterator> bi(
        icu::BreakIterator::createSentenceInstance(locale, status));
    if (U_FAILURE(status) || !bi) {
        *error = "createSentenceInstance failed";
        return false;
    }
    icu::UnicodeString utext(std::u16string(text).c_str());  // NUL is not in the corpus
    if (utext.length() != text.size()) { *error = "embedded NUL in corpus"; return false; }
    bi->setText(utext);
    out->clear();
    for (int32_t p = bi->first(); p != icu::BreakIterator::DONE; p = bi->next()) out->push_back(p);
    return true;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: %s <corpus.tsv> <goldens.tsv>\n", argv[0]);
        return 2;
    }
    std::vector<Case> cases;
    std::string error;
    if (!readCorpus(argv[1], &cases, &error)) {
        std::fprintf(stderr, "corpus error: %s\n", error.c_str());
        return 1;
    }

    std::ofstream out(argv[2], std::ios::binary);
    if (!out) { std::fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
    out << "# ICU sentence-break boundaries (UTF-16 code units) for sentence-corpus.tsv.\n"
        << "# Generated by tools/icu-sentence-golden/icu_sentence_golden.cpp, do not edit.\n"
        << "# ICU " << U_ICU_VERSION << ", Locale::getRoot() rules; verified equal to\n"
        << "# Locale::getDefault() at generation time. Format: <id>\\t0,end1,...,len\n";

    int mismatches = 0;
    for (const Case& c : cases) {
        std::vector<int32_t> root;
        std::vector<int32_t> def;
        if (!boundaries(icu::Locale::getRoot(), c.text, &root, &error) ||
            !boundaries(icu::Locale::getDefault(), c.text, &def, &error)) {
            std::fprintf(stderr, "break iteration failed for %s: %s\n", c.id.c_str(), error.c_str());
            return 1;
        }
        if (root != def) {
            std::fprintf(stderr, "locale-dependent boundaries for %s (root != %s)\n",
                         c.id.c_str(), icu::Locale::getDefault().getName());
            ++mismatches;
        }
        out << c.id;
        for (int32_t b : root) out << '\t' << b;
        out << '\n';
    }
    std::printf("%zu cases written to %s; locale-dependent: %d\n", cases.size(), argv[2], mismatches);
    return mismatches == 0 ? 0 : 1;
}
